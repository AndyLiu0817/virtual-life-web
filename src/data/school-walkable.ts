// Walkable lawn and pavement outlines are traced at half the source resolution.
// The first polygon is the outer playable boundary. Remaining polygons are exclusions.
function sourcePixels(polygons: readonly (readonly MapPoint[])[]) {
  return polygons.map((polygon) =>
    polygon.map(([x, y]): MapPoint => [2 * x, 2 * y]),
  );
}

