type Prompt = readonly [
  question: string,
  correct: string,
  distractor: string,
  distractor: string,
];
type Topic = readonly [
  name: string,
  first: Prompt,
  second: Prompt,
  third: Prompt,
];

function questions(
  ...topics: readonly [Topic, Topic, Topic, Topic, Topic, Topic]
) {
  return topics.flatMap(([topic, ...prompts], index) =>
    prompts.map(([text, ...choices], number) => ({
      id: `${index + 1}-${number + 1}`,
      topic,
      text,
      choices,
    })),
  );
}

